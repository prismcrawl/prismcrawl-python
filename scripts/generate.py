#!/usr/bin/env python3
"""Generate the typed models and endpoint classes from the PrismCrawl OpenAPI spec.

Usage:
    python scripts/generate.py            # regenerate from ./openapi.json
    python scripts/generate.py --fetch    # download the latest spec first

Writes src/prismcrawl/types.py and src/prismcrawl/_resources.py. Both files are
committed; CI fails if they drift from openapi.json.
"""

from __future__ import annotations

import argparse
import json
import keyword
import re
import textwrap
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent
SPEC_PATH = ROOT / "openapi.json"
SPEC_URL = "https://www.prismcrawl.com/openapi.json"
TYPES_OUT = ROOT / "src" / "prismcrawl" / "types.py"
RESOURCES_OUT = ROOT / "src" / "prismcrawl" / "_resources.py"

HEADER = "# Generated by scripts/generate.py from openapi.json. Do not edit by hand.\n"

# Enums longer than this become plain `str` so signatures stay readable.
MAX_LITERAL_ENUM = 40

# Word casing for generated class names.
WORD_CASE = {"duckduckgo": "DuckDuckGo"}

# Extra top-level attributes that point at an existing namespace.
NAMESPACE_ALIASES = {"bing": "microsoft"}


def pascal(value: str) -> str:
    words = [w for w in re.split(r"[^0-9A-Za-z]+", value) if w]
    return "".join(WORD_CASE.get(w.lower(), w[:1].upper() + w[1:]) for w in words)


def schema_name(name: str) -> str:
    if name.startswith("Catalog_"):
        return pascal(name[len("Catalog_") :])
    return name


def literal(value: Any) -> str:
    return json.dumps(value) if isinstance(value, str) else repr(value)


def ref_target(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def docstring(text: str, indent: str) -> str:
    text = text.strip().replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if text.endswith('"'):
        text += " "
    lines: List[str] = []
    for para in text.split("\n"):
        wrapped = textwrap.wrap(para, width=88 - len(indent)) or [""]
        lines.extend(wrapped)
    if len(lines) == 1:
        return f'{indent}"""{lines[0]}"""\n'
    body = "\n".join(f"{indent}{line}" if line else "" for line in lines)
    return f'{indent}"""\n{body}\n{indent}"""\n'


@dataclass
class TypedDictDef:
    name: str
    fields: List[Tuple[str, str, bool, str]]  # name, type, required, description
    description: str = ""


class TypeEmitter:
    """Turns JSON Schema into TypedDict classes and type expressions."""

    def __init__(self, spec: Dict[str, Any]) -> None:
        self.spec = spec
        self.schemas: Dict[str, Any] = spec["components"]["schemas"]
        self.names: Dict[str, str] = {}
        taken: Dict[str, str] = {}
        for raw in self.schemas:
            nice = schema_name(raw)
            if nice in taken:
                raise SystemExit(f"type name collision: {raw} and {taken[nice]} -> {nice}")
            taken[nice] = raw
            self.names[raw] = nice
        self.used = set(taken)
        self.typed_dicts: List[TypedDictDef] = []
        self.aliases: List[Tuple[str, str, str]] = []  # name, expr, description
        self.inline: Dict[int, str] = {}  # id(schema) -> generated TypedDict name

    def unique(self, name: str) -> str:
        candidate, n = name, 2
        while candidate in self.used:
            candidate, n = f"{name}{n}", n + 1
        self.used.add(candidate)
        return candidate

    def expr(self, schema: Any, context: str, prefix: str = "", quote: bool = False) -> str:
        """Return a type expression for `schema`, registering inline object types."""
        if not isinstance(schema, dict):
            return "Any"
        if "$ref" in schema:
            name = prefix + self.names[ref_target(schema["$ref"])]
            return f'"{name}"' if quote else name
        if "allOf" in schema:
            parts = schema["allOf"]
            if len(parts) == 1:
                return self.expr(parts[0], context, prefix, quote)
            return "Dict[str, Any]"
        for key in ("oneOf", "anyOf"):
            if key in schema:
                inline = [s for s in schema[key] if isinstance(s, dict) and s.get("properties")]
                members = []
                for i, sub in enumerate(schema[key]):
                    sub_ctx = context if len(inline) <= 1 else f"{context}{i + 1}"
                    members.append(self.expr(sub, sub_ctx, prefix, quote))
                return union(members)
        if "const" in schema:
            return f"Literal[{literal(schema['const'])}]"
        if "enum" in schema:
            values = [v for v in schema["enum"] if v is not None]
            nullable = len(values) != len(schema["enum"])
            # typing.Literal can't hold floats, e.g. Google Maps min_rating 2.5.
            if len(values) > MAX_LITERAL_ENUM or not values or any(isinstance(v, float) for v in values):
                base = self.primitive(schema.get("type"), schema, context, prefix, quote)
            else:
                base = f"Literal[{', '.join(literal(v) for v in values)}]"
            return f"Optional[{base}]" if nullable else base
        return self.primitive(schema.get("type"), schema, context, prefix, quote)

    def primitive(self, typ: Any, schema: Dict[str, Any], context: str, prefix: str, quote: bool) -> str:
        if isinstance(typ, list):
            members = [self.primitive(t, schema, context, prefix, quote) for t in typ]
            return union(members)
        if typ == "string":
            return "str"
        if typ == "integer":
            return "int"
        if typ == "number":
            return "float"
        if typ == "boolean":
            return "bool"
        if typ == "null":
            return "None"
        if typ == "array":
            item_ctx = context if context.endswith("Item") else f"{context}Item"
            return f"List[{self.expr(schema.get('items'), item_ctx, prefix, quote)}]"
        if typ == "object" or "properties" in schema:
            if schema.get("properties"):
                if id(schema) not in self.inline:
                    self.inline[id(schema)] = self.object_type(schema, self.unique(context))
                name = prefix + self.inline[id(schema)]
                return f'"{name}"' if quote else name
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict):
                return f"Dict[str, {self.expr(extra, context + 'Value', prefix, quote)}]"
            return "Dict[str, Any]"
        return "Any"

    def object_type(self, schema: Dict[str, Any], name: str) -> str:
        required = set(schema.get("required", []))
        fields = []
        for prop, sub in schema["properties"].items():
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", prop):
                raise SystemExit(f"{name}.{prop} is not a valid identifier; extend the generator")
            typ = self.expr(sub, name + pascal(prop))
            desc = sub.get("description", "") if isinstance(sub, dict) else ""
            fields.append((prop, typ, prop in required, desc))
        self.typed_dicts.append(TypedDictDef(name, fields, schema.get("description", "")))
        return name

    def emit_component(self, raw: str) -> None:
        schema = self.schemas[raw]
        name = self.names[raw]
        if schema.get("properties"):
            self.object_type(schema, name)
        else:
            self.aliases.append((name, self.expr(schema, name, quote=True), schema.get("description", "")))


def union(members: List[str]) -> str:
    seen: List[str] = []
    for m in members:
        if m not in seen:
            seen.append(m)
    nullable = "None" in seen
    rest = [m for m in seen if m != "None"]
    if not rest:
        return "None"
    inner = rest[0] if len(rest) == 1 else f"Union[{', '.join(rest)}]"
    return f"Optional[{inner}]" if nullable else inner


@dataclass
class Param:
    name: str
    schema: Dict[str, Any]
    required: bool
    description: str


@dataclass
class Endpoint:
    attr_path: List[str]
    path: str
    summary: str
    description: str
    request: str  # raw schema name
    response_expr: str  # type expression in the `types` module
    pagination: Optional[str]
    params: List[Param] = field(default_factory=list)

    @property
    def class_name(self) -> str:
        return "".join(pascal(p) for p in self.attr_path)


def attr_name(segment: str) -> str:
    return segment.replace("-", "_")


# Only accepted by submit(), where they're required.
WEBHOOK_PARAMS = ("webhook_url", "webhook_secret")


def collect_endpoints(spec: Dict[str, Any], emitter: TypeEmitter) -> List[Endpoint]:
    paths = spec["paths"]
    endpoints = []
    for path, item in paths.items():
        op = item.get("post")
        if op is None:
            continue
        if f"{path}/{{request_id}}" not in paths:
            raise SystemExit(f"{path} has no history endpoint; extend the generator")
        segments = path.strip("/").split("/")
        if segments[0] != "v1":
            raise SystemExit(f"unexpected path {path}")
        attr_path = [attr_name(s) for s in segments[1:]]

        req_ref = op["requestBody"]["content"]["application/json"]["schema"]["$ref"]
        request = ref_target(req_ref)
        req_schema = emitter.schemas[request]

        res_schema = op["responses"]["200"]["content"]["application/json"]["schema"]
        if "$ref" in res_schema:
            response_expr = emitter.names[ref_target(res_schema["$ref"])]
        else:
            alias = emitter.unique("".join(pascal(p) for p in attr_path) + "Response")
            emitter.aliases.append(
                (alias, emitter.expr(res_schema, alias, quote=True), op.get("summary", "") + " response.")
            )
            response_expr = alias

        props = req_schema.get("properties", {})
        required = set(req_schema.get("required", []))
        if "next_page_token" in props:
            pagination = "token"
        elif "page" in props:
            pagination = "page"
        else:
            pagination = None
        params = [
            Param(name, sub, name in required, sub.get("description", ""))
            for name, sub in props.items()
            if name not in WEBHOOK_PARAMS
        ]
        params.sort(key=lambda p: not p.required)
        endpoints.append(
            Endpoint(
                attr_path,
                path,
                op.get("summary", ""),
                op.get("description", ""),
                request,
                response_expr,
                pagination,
                params,
            )
        )
    endpoints.sort(key=lambda e: e.attr_path)
    return endpoints


def render_types(emitter: TypeEmitter) -> str:
    out = [
        HEADER,
        '"""Request and response types for the PrismCrawl API.\n\n'
        "Responses are plain dicts at runtime; these TypedDicts exist for editor\n"
        'completion and static type checking."""\n\n',
        "from __future__ import annotations\n\n",
        "from typing import Any, Dict, List, Optional, Union\n\n",
        "from typing_extensions import Literal, Required, TypedDict\n\n",
    ]
    names = sorted([t.name for t in emitter.typed_dicts] + [a[0] for a in emitter.aliases])
    out.append("__all__ = [\n" + "".join(f'    "{n}",\n' for n in names) + "]\n")
    for td in emitter.typed_dicts:
        if any(not name.isidentifier() or keyword.iskeyword(name) for name, *_ in td.fields):
            # Field names like `from` need the functional syntax.
            out.append(f"\n\n{td.name} = TypedDict(\n    {json.dumps(td.name)},\n    {{\n")
            for name, typ, required, _desc in td.fields:
                out.append(f"        {json.dumps(name)}: {'Required[' + typ + ']' if required else typ},\n")
            out.append("    },\n    total=False,\n)\n")
            if td.description:
                out.append(docstring(td.description, ""))
            continue
        out.append(f"\n\nclass {td.name}(TypedDict, total=False):\n")
        if td.description:
            out.append(docstring(td.description, "    "))
            if td.fields:
                out.append("\n")
        if not td.fields:
            out.append("    pass\n")
        for i, (name, typ, required, desc) in enumerate(td.fields):
            out.append(f"    {name}: {'Required[' + typ + ']' if required else typ}\n")
            if desc:
                out.append(docstring(desc, "    "))
            if desc and i < len(td.fields) - 1:
                out.append("\n")
    out.append("\n")
    for name, expr, desc in emitter.aliases:
        out.append(f"\n{name} = {expr}\n")
        if desc:
            out.append(docstring(desc, ""))
    return "".join(out)


def param_annotation(emitter: TypeEmitter, endpoint: Endpoint, param: Param) -> str:
    typ = emitter.expr(param.schema, emitter.names[endpoint.request] + pascal(param.name), prefix="t.")
    if param.required:
        return typ
    return typ if typ.startswith("Optional[") else f"Optional[{typ}]"


def render_signature(emitter: TypeEmitter, endpoint: Endpoint, *extra: str) -> str:
    lines = ["self", "*"]
    lines.extend(e for e in extra if "=" not in e)
    for p in endpoint.params:
        ann = param_annotation(emitter, endpoint, p)
        lines.append(f"{p.name}: {ann}" if p.required else f"{p.name}: {ann} = None")
    lines.extend(e for e in extra if "=" in e)
    lines.append("extra_body: Optional[Mapping[str, Any]] = None")
    lines.append("timeout: Optional[float] = None")
    return "".join(f"        {line},\n" for line in lines)


def render_args_doc(endpoint: Endpoint, *extra: Tuple[str, str]) -> str:
    rows = []
    for p in endpoint.params:
        desc = " ".join(p.description.split()) or "See the API reference."
        rows.append((p.name, desc))
    rows.extend(extra)
    rows.append(("extra_body", "Additional JSON fields to send, for parameters newer than this SDK."))
    rows.append(("timeout", "Override the client timeout for this call, in seconds."))
    out = ["Args:"]
    for name, desc in rows:
        wrapped = textwrap.wrap(f"{name}: {desc}", width=76)
        out.append("    " + wrapped[0])
        out.extend("        " + w for w in wrapped[1:])
    return "\n".join(out)


def render_body(endpoint: Endpoint, extra: Tuple[str, ...] = ()) -> str:
    names = [*extra, *(p.name for p in endpoint.params)]
    items = "".join(f'            "{name}": {name},\n' for name in names)
    return f"        body = {{\n{items}        }}\n"


def method_doc(text: str) -> str:
    return docstring(text, "        ")


def render_endpoint_class(
    emitter: TypeEmitter, endpoint: Endpoint, is_async: bool, children: Optional[Namespace] = None
) -> str:
    prefix = "Async" if is_async else ""
    cls = prefix + endpoint.class_name
    base = "AsyncEndpoint" if is_async else "SyncEndpoint"
    res = f"t.{endpoint.response_expr}"
    out = [f"\n\nclass {cls}({base}):\n"]
    out.append(docstring(f"{endpoint.summary}: ``POST {endpoint.path}``.", "    "))
    out.append(f'\n    _path = "{endpoint.path}"\n')
    if endpoint.pagination:
        out.append(f'    _pagination = "{endpoint.pagination}"\n')
    if children is not None:
        # Related endpoints nest under this one, e.g. google.images.light(...).
        out.append(f"\n    def __init__(self, client: {prefix}BaseClient) -> None:\n")
        out.append("        super().__init__(client)\n")
        out.append(render_attachments(children, prefix))
    head = f"{endpoint.summary}.\n\n{endpoint.description}".strip()

    out.append(
        f"\n    {'async ' if is_async else ''}def __call__(\n{render_signature(emitter, endpoint)}    ) -> {res}:\n"
    )
    out.append(method_doc(f"{head}\n\n{render_args_doc(endpoint)}"))
    out.append(render_body(endpoint))
    call = "await self._create" if is_async else "self._create"
    out.append(f"        return {call}(body, extra_body, timeout)\n")

    submit_extra = (
        "webhook_url: str",
        "webhook_secret: str",
        "idempotency_key: Optional[str] = None",
    )
    submit_doc = (
        f"Run {endpoint.summary} asynchronously.\n\n"
        "Returns a job receipt once PrismCrawl accepts the request. The completed\n"
        "response is POSTed to ``webhook_url``, signed with ``webhook_secret``; check it\n"
        "with :func:`prismcrawl.verify_webhook`. A receipt doesn't mean the search\n"
        "succeeded. Takes the same parameters as calling the endpoint, plus:\n\n"
        "Args:\n"
        "    webhook_url: Public HTTPS URL that receives the completed response by POST.\n"
        "    webhook_secret: Shared secret (32 to 256 printable ASCII characters) used to\n"
        "        sign deliveries.\n"
        "    idempotency_key: Identifies this submission so retries can't start a second\n"
        "        search. Defaults to a new UUID. Reuse it, with identical parameters, to\n"
        "        retry an uncertain submission."
    )
    out.append(
        f"\n    {'async ' if is_async else ''}def submit(\n"
        f"{render_signature(emitter, endpoint, *submit_extra)}    ) -> AsyncReceipt:\n"
    )
    out.append(method_doc(submit_doc))
    out.append(render_body(endpoint, WEBHOOK_PARAMS))
    submit_call = "await self._submit" if is_async else "self._submit"
    out.append(f"        return {submit_call}(body, extra_body, timeout, idempotency_key)\n")

    if endpoint.pagination:
        iterator = "AsyncIterator" if is_async else "Iterator"
        extra = "max_pages: Optional[int] = None"
        pages_doc = (
            f"Iterate over pages of {endpoint.summary} results.\n\n"
            "Follows the response's pagination until ``has_next_page`` is false or\n"
            "``max_pages`` pages have been fetched. Each page is a separate request\n"
            "and uses one credit.\n\n"
            + render_args_doc(endpoint, ("max_pages", "Stop after this many pages. Defaults to no limit."))
        )
        out.append(f"\n    def pages(\n{render_signature(emitter, endpoint, extra)}    ) -> {iterator}[{res}]:\n")
        out.append(method_doc(pages_doc))
        out.append(render_body(endpoint))
        out.append("        return self._pages(body, extra_body, timeout, max_pages)\n")
    return "".join(out)


@dataclass
class Namespace:
    path: List[str]
    children: Dict[str, Namespace] = field(default_factory=dict)
    endpoints: Dict[str, Endpoint] = field(default_factory=dict)

    @property
    def class_name(self) -> str:
        return "".join(pascal(p) for p in self.path) + "Resource"


def build_tree(endpoints: List[Endpoint]) -> Namespace:
    root = Namespace([])
    for ep in endpoints:
        node = root
        for seg in ep.attr_path[:-1]:
            node = node.children.setdefault(seg, Namespace(node.path + [seg]))
        node.endpoints[ep.attr_path[-1]] = ep
    check_nesting(root)
    return root


# An endpoint's children become attributes of it, so they can't shadow its methods.
RESERVED_CHILD_NAMES = {"get", "pages", "submit"}


def check_nesting(ns: Namespace) -> None:
    for name, child in ns.children.items():
        if name in ns.endpoints:
            for key in [*child.children, *child.endpoints]:
                if key in RESERVED_CHILD_NAMES or key.startswith("_"):
                    raise SystemExit(f"{'.'.join(child.path + [key])} collides with an endpoint method")
        check_nesting(child)


def nested_children(ns: Namespace) -> Dict[str, Namespace]:
    """Map each endpoint path to the namespace of endpoints nested under it."""
    out: Dict[str, Namespace] = {}
    for name, child in ns.children.items():
        if name in ns.endpoints:
            out[ns.endpoints[name].path] = child
        out.update(nested_children(child))
    return out


def render_attachments(ns: Namespace, prefix: str) -> str:
    out = []
    for name, child in sorted(ns.children.items()):
        if name not in ns.endpoints:
            out.append(f"        self.{name} = {prefix}{child.class_name}(client)\n")
    for name, ep in sorted(ns.endpoints.items()):
        out.append(f"        self.{name} = {prefix}{ep.class_name}(client)\n")
    return "".join(out)


def walk(ns: Namespace, merged: bool = False) -> List[Namespace]:
    """Namespaces that need their own class; ones nested under an endpoint don't."""
    out = []
    for name, child in ns.children.items():
        out.extend(walk(child, merged=name in ns.endpoints))
    if not merged:
        out.append(ns)
    return out


def render_namespace(ns: Namespace, is_async: bool) -> str:
    prefix = "Async" if is_async else ""
    is_root = not ns.path
    cls = f"{prefix}Resources" if is_root else prefix + ns.class_name
    out = [f"\n\nclass {cls}:\n"]
    if is_root:
        out.append('    """Attaches every API namespace to a client."""\n\n')
        out.append(f"    def _init_resources(self, client: {prefix}BaseClient) -> None:\n")
    else:
        label = " ".join(pascal(p) for p in ns.path)
        out.append(f'    """{label} endpoints."""\n\n')
        out.append(f"    def __init__(self, client: {prefix}BaseClient) -> None:\n")
    out.append(render_attachments(ns, prefix))
    if is_root:
        for alias, target in NAMESPACE_ALIASES.items():
            out.append(f"        self.{alias} = self.{target}\n")
    return "".join(out)


def render_resources(endpoints: List[Endpoint], emitter: TypeEmitter) -> str:
    tree = build_tree(endpoints)
    out = [
        HEADER,
        '"""Endpoint classes for every PrismCrawl API operation."""\n\n',
        "from __future__ import annotations\n\n",
        "from typing import Any, AsyncIterator, Iterator, List, Mapping, Optional, Union\n\n",
        "from typing_extensions import Literal\n\n",
        "from . import types as t\n",
        "from ._base import AsyncBaseClient, BaseClient\n",
        "from ._async import AsyncReceipt\n",
        "from ._endpoint import AsyncEndpoint, SyncEndpoint\n",
    ]
    nested = nested_children(tree)
    for ep in endpoints:
        out.append(render_endpoint_class(emitter, ep, is_async=False, children=nested.get(ep.path)))
    for ns in walk(tree):
        out.append(render_namespace(ns, is_async=False))
    for ep in endpoints:
        out.append(render_endpoint_class(emitter, ep, is_async=True, children=nested.get(ep.path)))
    for ns in walk(tree):
        out.append(render_namespace(ns, is_async=True))
    return "".join(out)


FORMATS = {"json", "md", "html+br+base64"}


def clean_spec(node: Any) -> None:
    """Drop the published spec's zero-default alternative from ``format`` discriminators.

    The spec marks response constants as "value or zero default", which turns
    ``data.format`` into ``"" | "json"``. The API never sends an empty format.
    """
    if isinstance(node, list):
        for item in node:
            clean_spec(item)
        return
    if not isinstance(node, dict):
        return
    fmt = (node.get("properties") or {}).get("format")
    if isinstance(fmt, dict) and len(fmt.get("anyOf", [])) == 2:
        kept = [a for a in fmt["anyOf"] if a.get("const") != ""]
        if len(kept) == 1 and kept[0].get("const") in FORMATS:
            node["properties"]["format"] = {
                **kept[0],
                **({"description": fmt["description"]} if "description" in fmt else {}),
            }
    for value in node.values():
        clean_spec(value)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--fetch", action="store_true", help=f"download {SPEC_URL} first")
    args = parser.parse_args()
    if args.fetch:
        with urllib.request.urlopen(SPEC_URL) as resp:  # noqa: S310
            spec_text = resp.read().decode("utf-8")
        SPEC_PATH.write_text(json.dumps(json.loads(spec_text), indent=2) + "\n")
    spec = json.loads(SPEC_PATH.read_text())
    clean_spec(spec)

    emitter = TypeEmitter(spec)
    for raw in emitter.schemas:
        emitter.emit_component(raw)
    endpoints = collect_endpoints(spec, emitter)
    resources = render_resources(endpoints, emitter)
    types = render_types(emitter)

    TYPES_OUT.write_text(types)
    RESOURCES_OUT.write_text(resources)
    print(f"Generated {len(endpoints)} endpoints and {len(emitter.typed_dicts) + len(emitter.aliases)} types.")


if __name__ == "__main__":
    main()
